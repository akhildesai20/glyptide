#!/usr/bin/env node
/**
 * Sync install / publication wording from docs/publication-status.json.
 * Regenerates AI docs install notes; prints the README snippet to paste if needed.
 * Does not publish anything.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const statusPath = path.join(root, "docs/publication-status.json");
const status = JSON.parse(fs.readFileSync(statusPath, "utf8"));

function installBlock() {
  if (status.npmPublished) {
    return {
      headline: `\`${status.packages[0]}@${status.version}\` is on the public npm registry.`,
      bash: `# Core
npm install glyptide

# Optional React adapter
npm install @glyptide/react`,
    };
  }
  return {
    headline: `\`${status.packages[0]}@${status.version}\` is **not on the public npm registry yet**. Install a built package path or tarball:`,
    bash: `# From a clone after \`npm run build:lib\` (paths work on macOS, Linux, and Windows):
npm install ./packages/glyptide

# Optional React adapter:
npm install ./packages/glyptide-react

# Or pack once, then install anywhere without the rest of the tree:
#   cd packages/glyptide && npm pack
#   npm install ./glyptide-${status.version}.tgz`,
  };
}

const block = installBlock();
const out = path.join(root, "docs/publication-install.md");
fs.writeFileSync(
  out,
  `# Installation (generated)

> Source of truth: \`docs/publication-status.json\` (\`npmPublished: ${status.npmPublished}\`).  
> Do not edit this file by hand — run \`npm run sync:publication-status\`.

${block.headline}

\`\`\`bash
${block.bash}
\`\`\`
`,
);

const gen = spawnSync("node", [path.join(root, "scripts/generate-ai-docs.mjs")], {
  cwd: root,
  stdio: "inherit",
  shell: process.platform === "win32",
});
if (gen.status !== 0) process.exit(gen.status ?? 1);

console.log(`\nPublication status: npmPublished=${status.npmPublished} maturity=${status.maturity}`);
console.log(`Wrote ${path.relative(root, out)}`);
console.log("Regenerated AI docs. Update root/package READMEs if their install blocks drifted.");
